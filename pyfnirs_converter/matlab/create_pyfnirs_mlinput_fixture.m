fid = fopen(jsonPath, 'w', 'n', 'UTF-8');
if fid < 0
    error('PYfNIRs:ExpectedOpenFailed', 'Cannot create expected values file: %s', jsonPath);
end
fileCleanup = onCleanup(@() fclose(fid));
fwrite(fid, jsonencode(expected), 'char');
fwrite(fid, newline, 'char');
clear fileCleanup;
end
